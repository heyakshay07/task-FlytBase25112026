"""Scalability test: push N synthetic frames through the full pipeline and time everything.

    python scripts/scalability_test.py --frames 50000 --db output/scale.db

Frames are generated by replaying the scripted scenario over many simulated days with
randomised captions so entities vary. Reports ingest throughput, DB size, peak RSS, context
size (should stay flat) and query latency on the populated index.
"""
from __future__ import annotations

import argparse
import ctypes
import json
import os
import random
import sys
import time
from datetime import datetime, timedelta

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from drone_analyst.agent import SecurityAnalystAgent  # noqa: E402
from drone_analyst.indexer import FrameIndex  # noqa: E402
from drone_analyst.models import Frame, Telemetry  # noqa: E402
from drone_analyst.simulator import SCENARIO, WAYPOINTS  # noqa: E402

COLORS = ["blue", "red", "white", "black", "silver", "green"]
CARS = ["Ford F150", "Toyota Hilux", "Honda Civic", "Tata Nexon", "Maruti Swift", "Hyundai Creta"]
IDLE = ["Empty driveway. No activity.", "Garage door closed. No activity.", "Quiet perimeter, no movement."]


def synth(n: int, seed: int = 1):
    rng = random.Random(seed)
    t = datetime(2026, 1, 1)
    locs = list(WAYPOINTS)
    for i in range(1, n + 1):
        t += timedelta(minutes=rng.choice([1, 1, 2, 5]))
        r = rng.random()
        loc = rng.choice(locs)
        if r < 0.55:
            cap = rng.choice(IDLE)
        elif r < 0.75:
            cap = f"{rng.choice(COLORS).capitalize()} {rng.choice(CARS)} {rng.choice(['enters through main gate', 'parked at garage', 'leaves through main gate'])}."
        elif r < 0.9:
            cap = rng.choice(["Person in dark hoodie standing at main gate.", "Gardener in green uniform trimming hedge.",
                              "Courier carrying package.", "Person in grey cap walking along the fence."])
        elif r < 0.97:
            cap = rng.choice(SCENARIO)[2]
        else:
            cap = "Person in black jacket climbing over perimeter fence with a ladder."
        x, y = WAYPOINTS[loc]
        yield Frame(i, t, Telemetry(loc, x, y, rng.uniform(15, 35), rng.uniform(30, 100)), cap)


def rss_mb() -> float:
    if os.name == "nt":
        from ctypes import wintypes

        class ProcessMemoryCounters(ctypes.Structure):
            _fields_ = [
                ("cb", wintypes.DWORD),
                ("PageFaultCount", wintypes.DWORD),
                ("PeakWorkingSetSize", ctypes.c_size_t),
                ("WorkingSetSize", ctypes.c_size_t),
                ("QuotaPeakPagedPoolUsage", ctypes.c_size_t),
                ("QuotaPagedPoolUsage", ctypes.c_size_t),
                ("QuotaPeakNonPagedPoolUsage", ctypes.c_size_t),
                ("QuotaNonPagedPoolUsage", ctypes.c_size_t),
                ("PagefileUsage", ctypes.c_size_t),
                ("PeakPagefileUsage", ctypes.c_size_t),
                ("PrivateUsage", ctypes.c_size_t),
            ]

        counters = ProcessMemoryCounters()
        counters.cb = ctypes.sizeof(counters)
        kernel32 = ctypes.WinDLL("Kernel32.dll", use_last_error=True)
        psapi = ctypes.WinDLL("Psapi.dll", use_last_error=True)
        kernel32.GetCurrentProcess.restype = wintypes.HANDLE
        psapi.GetProcessMemoryInfo.argtypes = [
            wintypes.HANDLE, ctypes.POINTER(ProcessMemoryCounters), wintypes.DWORD,
        ]
        psapi.GetProcessMemoryInfo.restype = wintypes.BOOL
        if not psapi.GetProcessMemoryInfo(kernel32.GetCurrentProcess(), ctypes.byref(counters), counters.cb):
            raise ctypes.WinError(ctypes.get_last_error())
        return counters.PeakWorkingSetSize / (1024 * 1024)

    import resource
    peak = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    return peak / (1024 * 1024 if sys.platform == "darwin" else 1024)


def timeit(fn, reps=5):
    best = []
    for _ in range(reps):
        s = time.perf_counter(); out = fn(); best.append((time.perf_counter() - s) * 1000)
    return sum(best) / len(best), out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--frames", type=int, default=50000)
    ap.add_argument("--db", default="output/scale.db")
    ap.add_argument("--json", default="")
    a = ap.parse_args()

    agent = SecurityAnalystAgent(FrameIndex(a.db, reset=True, commit_every=2000))
    ctx_sizes, t0, alerts = [], time.perf_counter(), 0
    marks = {}
    for k, f in enumerate(synth(a.frames), start=1):
        alerts += len(agent.ingest(f).alerts)
        if k % (a.frames // 5) == 0:
            ctx_sizes.append(len(agent.ctx.prompt_context()))
            marks[k] = (time.perf_counter() - t0, rss_mb())
    agent.index.flush()
    total = time.perf_counter() - t0

    q = {}
    q["object query: truck (all events)"] = timeit(lambda: len(agent.index.frames(obj="truck", limit=100000)))
    q["time-of-day query: 22:00-05:00"] = timeit(lambda: len(agent.index.frames(tod_start="22:00", tod_end="05:00", limit=100000)))
    q["full-text search: 'hedge'"] = timeit(lambda: len(agent.index.text_search("hedge", 10)))
    q["semantic search: 'break in'"] = timeit(lambda: len(agent.index.semantic_search("someone trying to break in", 5)))
    q["alerts >= CRITICAL"] = timeit(lambda: len(agent.index.alerts(__import__("drone_analyst.models", fromlist=["Severity"]).Severity.CRITICAL, limit=10**6)))
    q["Q&A: how many times did the truck enter"] = timeit(lambda: len(agent.ask("how many times did the truck enter").text))

    res = {"frames": a.frames, "ingest_seconds": round(total, 2), "frames_per_second": round(a.frames / total),
           "alerts": alerts, "db_mb": round(os.path.getsize(a.db) / 1e6, 1), "peak_rss_mb": round(rss_mb(), 1),
           "entities_tracked": len(agent.ctx.entities), "context_chars_at_20/40/60/80/100pct": ctx_sizes,
           "queries_ms": {k: {"avg_ms": round(v[0], 1), "rows": v[1]} for k, v in q.items()}}
    print(json.dumps(res, indent=2))
    if a.json:
        with open(a.json, "w") as fh:
            json.dump(res, fh, indent=2)


if __name__ == "__main__":
    main()
